import assert from "node:assert/strict";
import {interpretUntrustedDoorUrl,buildPublicDoorLink} from "../market/a-1204/door-link.mjs";
const entry="https://example.invalid/estate/belgaum/A-1204?entry=vsr-door&buyer=Dubai&geo=dubai-pack&disclosure=qualified&state=FINISHED&anchor=FLOOR_01&river=river://a-1204/door/vsr%23entry";
const x=interpretUntrustedDoorUrl(entry);
assert.equal(x.requested_state,"FINISHED");
assert.equal(x.requested_anchor,"FLOOR_01");
assert.equal(x.geo_pack_hint,"dubai-pack");
assert.equal(x.effective_disclosure,"GUEST");
assert.equal(x.admitted,false);
assert.equal(x.evidence_verified,false);
assert.equal(x.booking_confirmed,false);
assert.equal(x.title_transferred,false);
assert.deepEqual(x.ignored_authority_inputs,["buyer","disclosure","river"]);
const invalid=interpretUntrustedDoorUrl("https://example.invalid/x?state=DELIVERED&anchor=ADMIN&disclosure=VERIFIED&rights=OWNER");
assert.equal(invalid.requested_anchor,null);
assert.equal(invalid.effective_disclosure,"GUEST");
assert.equal(invalid.title_transferred,false);
const link=buildPublicDoorLink("https://example.invalid",{state:"FINISHED",anchor:"FLOOR_01",locale:"ar-AE"});
assert.equal(new URL(link).searchParams.get("anchor"),"FLOOR_01");
assert.equal(new URL(link).searchParams.get("locale"),"ar-AE");
assert.equal(new URL(link).searchParams.has("disclosure"),false);
assert.equal(new URL(link).searchParams.has("river"),false);
assert.throws(()=>buildPublicDoorLink("http://example.invalid"),/HTTPS/);
assert.throws(()=>buildPublicDoorLink("https://example.invalid",{anchor:"ADMIN"}),/Invalid anchor/);
assert.throws(()=>interpretUntrustedDoorUrl("vsr://estate/belgaum/A-1204/door"),/Only web/);
console.log("PASS: public VSR Door URLs do not grant roles, evidence, booking or title rights.");
